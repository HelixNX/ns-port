def _compile():
    table = []
    for name, pat in OPCODES:
        assert len(pat) == 16, name
        mask = val = 0
        for i, ch in enumerate(pat):
            bit = 15 - i
            if ch != '-':
                mask |= 1 << bit
                if ch == '1':
                    val |= 1 << bit
        table.append((bin(mask).count('1'), mask, val, name))
    table.sort(key=lambda t: -t[0])
    return [(m, v, n) for _, m, v, n in table]


_TABLE = _compile()
_CACHE = {}


def opcode(insn):
    top = insn >> 48
    n = _CACHE.get(top)
    if n is None:
        n = '?'
        for m, v, name in _TABLE:
            if top & m == v:
                n = name
                break
        _CACHE[top] = n
    return n


def bits(x, lo, n):
    return (x >> lo) & ((1 << n) - 1)


class Shader:
    """A dumped shader: control section, code, SPH, instructions."""

    def __init__(self, path):
        data = open(path, 'rb').read()
        magic, csize, size, stage = struct.unpack_from('<4I', data)
        assert magic == 0x48534b4d, path
        self.path = path
        self.control = data[16:16 + csize]
        self.code = data[16 + csize:16 + csize + size]
        self.stage = STAGES[stage]
        c = self.control
        self.code_size, self.const_size, self.const_off, self.end = struct.unpack_from('<4I', c, 0x6f8)
        self.num_gprs = struct.unpack_from('<I', c, 0x70c)[0]
        self.graphics = struct.unpack_from('<I', self.code, 0)[0] == 0x12345678
        self.start = 0x80 if self.graphics else 0          # compute: no NVN header, no SPH
        self.sph = self.code[0x30:0x80] if self.graphics else None
        n = ((0x30 if self.graphics else 0) + self.code_size - self.start) // 8
        self.words = list(struct.unpack_from('<%dQ' % n, self.code, self.start))
        self.consts = self.code[self.const_off:self.const_off + self.const_size] if self.const_size else b''

    def local_memory_size(self):
        if not self.sph:
            return 0
        w1, w2 = struct.unpack_from('<II', self.sph, 4)
        return (w1 & 0xffffff) | (w2 & 0xffffff) << 24

    def instructions(self):
        """(pc, word) of every instruction (scheduling words skipped); pc is the byte offset from the start"""
        for i, w in enumerate(self.words):
            if i % 4 == 0:
                continue
            yield i * 8, w
