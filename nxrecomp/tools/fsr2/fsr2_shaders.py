"""AMD FSR 2's compute shaders for its Vulkan backend, without its permutation compiler.

FSR 2.2's Vulkan backend (deps/FidelityFX-FSR2, ffx_fsr2_vk.cpp) asks fsr2GetPermutationBlobByIndexVK for each pass's
SPIR-V and a description of its resources (the names and bindings of its storage images, sampled images and uniform
buffers), which AMD's build makes with FidelityFX_SC.exe for every combination of options. We fix the options we use
and build only those: LDR (tone-mapped) colour in, motion vectors at the render size and not jittered, 32-bit maths;
depth inverted or not, sharpening on or off, and the reprojection's Lanczos as a table or computed (the backend asks
for the table on wave64 devices: AMD) are the eight variants of each pass. glslang
compiles them (as AMD's tool does: -S comp, Vulkan 1.1, -Os), spirv-cross --reflect gives the resources.

Usage: fsr2_shaders.py <FSR 2 shaders folder> <glslangValidator> <spirv-cross> <out.cpp>
"""
import json
import os
import subprocess
import sys
import tempfile

PASSES = [   # FfxFsr2Pass order: (enum, shader)
    ('FFX_FSR2_PASS_DEPTH_CLIP', 'ffx_fsr2_depth_clip_pass'),
    ('FFX_FSR2_PASS_RECONSTRUCT_PREVIOUS_DEPTH', 'ffx_fsr2_reconstruct_previous_depth_pass'),
    ('FFX_FSR2_PASS_LOCK', 'ffx_fsr2_lock_pass'),
    ('FFX_FSR2_PASS_ACCUMULATE', 'ffx_fsr2_accumulate_pass'),
    ('FFX_FSR2_PASS_ACCUMULATE_SHARPEN', 'ffx_fsr2_accumulate_pass'),
    ('FFX_FSR2_PASS_RCAS', 'ffx_fsr2_rcas_pass'),
    ('FFX_FSR2_PASS_COMPUTE_LUMINANCE_PYRAMID', 'ffx_fsr2_compute_luminance_pyramid_pass'),
    ('FFX_FSR2_PASS_GENERATE_REACTIVE', 'ffx_fsr2_autogen_reactive_pass'),
    ('FFX_FSR2_PASS_TCR_AUTOGENERATE', 'ffx_fsr2_tcr_autogen_pass'),
]
# AMD's own base arguments (src/ffx-fsr2-api/CMakeLists.txt FFX_SC_BASE_ARGS), then our choice of the permutation ones
FIXED = {'FFX_GPU': 1, 'FFX_GLSL': 1, 'FFX_FSR2_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF': 0,
         'FFX_FSR2_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF': 0, 'FFX_FSR2_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF': 1,
         'FFX_FSR2_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF': 0, 'FFX_FSR2_OPTION_UPSAMPLE_USE_LANCZOS_TYPE': 2,
         'FFX_FSR2_OPTION_HDR_COLOR_INPUT': 0, 'FFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS': 1,
         'FFX_FSR2_OPTION_JITTERED_MOTION_VECTORS': 0, 'FFX_HALF': 0}


def build(src_dir, glslang, cross, shader, depth_inv, sharpen, lut, tmp):
    defs = dict(FIXED, FFX_FSR2_OPTION_INVERTED_DEPTH=depth_inv, FFX_FSR2_OPTION_APPLY_SHARPENING=sharpen,
                FFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE=lut)
    spv = os.path.join(tmp, '%s_%d%d%d.spv' % (shader, depth_inv, sharpen, lut))
    cmd = [glslang, '-V', '--target-env', 'vulkan1.1', '-S', 'comp', '-e', 'main', '-Os', '-I' + src_dir, '-o', spv]
    cmd += ['-D%s=%d' % kv for kv in defs.items()]
    cmd.append(os.path.join(src_dir, shader + '.glsl'))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit('glslang failed on %s:\n%s%s' % (shader, r.stdout, r.stderr))
    refl = json.loads(subprocess.run([cross, spv, '--reflect'], capture_output=True, text=True, check=True).stdout)
    data = open(spv, 'rb').read()

    def res(kind):
        out = []
        for v in refl.get(kind, []):
            if v.get('set', 0) != 1:              # set 0: the two static samplers (the backend's own)
                continue
            name = v['name']
            if kind == 'ubos' and name.endswith('_t'):     # the block's type name, cbFSR2_t -> cbFSR2
                name = name[:-2]
            out.append((name, v['binding']))
        return sorted(out, key=lambda nb: nb[1])
    return data, res('images'), res('separate_images'), res('ubos')


def main():
    src_dir, glslang, cross, out = sys.argv[1:5]
    blobs = {}                                   # (shader, depth_inv, sharpen, lut) -> c identifier
    lines = ['/* generated by nxrecomp/tools/fsr2/fsr2_shaders.py from AMD FidelityFX FSR 2 (MIT) -- do not edit */',
             '#include <stdint.h>', '#include "ffx_fsr2_shaders_vk.h"', '']
    with tempfile.TemporaryDirectory() as tmp:
        for shader in dict.fromkeys(s for _, s in PASSES):
            for depth_inv, sharpen, lut in ((d, s, l) for d in (0, 1) for s in (0, 1) for l in (0, 1)):
                data, uav, srv, cb = build(src_dir, glslang, cross, shader, depth_inv, sharpen, lut, tmp)
                cid = '%s_%d%d%d' % (shader, depth_inv, sharpen, lut)
                blobs[(shader, depth_inv, sharpen, lut)] = cid
                words = ['0x%02x' % b for b in data]
                lines.append('static const uint8_t %s_spv[%d] = {' % (cid, len(data)))
                lines += ['    ' + ', '.join(words[i:i + 24]) + ',' for i in range(0, len(words), 24)]
                lines.append('};')
                for tag, lst in (('uav', uav), ('srv', srv), ('cb', cb)):
                    if lst:
                        lines.append('static const char *%s_%s_names[] = {%s};' % (
                            cid, tag, ', '.join('"%s"' % n for n, _ in lst)))
                        lines.append('static const uint32_t %s_%s_bindings[] = {%s};' % (
                            cid, tag, ', '.join(str(b) for _, b in lst)))
                ref = lambda tag, lst, what: ('%s_%s_%s' % (cid, tag, what)) if lst else '0'
                lines.append('static const Fsr2ShaderBlobVK %s_blob = {%s_spv, %d, %d, %d, %d, %s, %s, %s, %s, %s, %s};' % (
                    cid, cid, len(data), len(uav), len(srv), len(cb), ref('uav', uav, 'names'),
                    ref('uav', uav, 'bindings'), ref('srv', srv, 'names'), ref('srv', srv, 'bindings'),
                    ref('cb', cb, 'names'), ref('cb', cb, 'bindings')))
                lines.append('')
    lines += ['/* the options outside the fixed set (fsr2_shaders.py FIXED) have no blob: an empty one, which fails the',
              ' * context creation instead of running a shader built for other options (FP16 and wave64 are hints: ignored) */',
              'Fsr2ShaderBlobVK fsr2GetPermutationBlobByIndexVK(FfxFsr2Pass pass, uint32_t o) {',
              '    Fsr2ShaderBlobVK none = {0};',
              '    if (o & (FSR2_SHADER_PERMUTATION_HDR_COLOR_INPUT | FSR2_SHADER_PERMUTATION_JITTER_MOTION_VECTORS) ||',
              '        !(o & FSR2_SHADER_PERMUTATION_LOW_RES_MOTION_VECTORS))',
              '        return none;',
              '    int i = ((o & FSR2_SHADER_PERMUTATION_DEPTH_INVERTED) ? 4 : 0) | ((o & FSR2_SHADER_PERMUTATION_ENABLE_SHARPENING) ? 2 : 0) |',
              '            ((o & FSR2_SHADER_PERMUTATION_REPROJECT_USE_LANCZOS_TYPE) ? 1 : 0);',
              '    switch (pass) {']
    for enum, shader in PASSES:
        lines.append('    case %s:' % enum)
        lines.append('        { static const Fsr2ShaderBlobVK *const b[8] = {%s}; return *b[i]; }' % ', '.join(
            '&%s_blob' % blobs[(shader, (k >> 2) & 1, (k >> 1) & 1, k & 1)] for k in range(8)))
    lines += ['    default:', '        return none;', '    }', '}', '']
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    text = '\n'.join(lines)
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    open(out, 'w').write(text)


if __name__ == '__main__':
    main()
